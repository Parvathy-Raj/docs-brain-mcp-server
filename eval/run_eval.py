"""Measure retrieval quality for each mode and write a Markdown results table.

Run:  python eval/run_eval.py            (all modes)
      python eval/run_eval.py --misses   (also list the questions each mode got wrong)

A question counts as a hit at k when any of its expected pages is among the top k chunks.
Questions come in two sets:
  broad    - "which page covers X" questions (25)
  specific - questions about one fact inside a page (15)
"""

from __future__ import annotations

import argparse
import json
import statistics
import time
from pathlib import Path

from docs_brain import config
from docs_brain.retrieve import Retriever

QUESTIONS = Path(__file__).with_name("questions.jsonl")
RESULTS = Path(__file__).with_name("results.md")
K = 5

# (label, mode, reranker model)
CONFIGS = [
    ("Dense only (bge-small)", "dense", None),
    ("BM25 only", "bm25", None),
    ("Hybrid (dense + BM25, RRF)", "hybrid", None),
    ("Hybrid + bge-reranker-base", "hybrid_rerank", "BAAI/bge-reranker-base"),
    ("Hybrid + MiniLM-L6 reranker", "hybrid_rerank", "cross-encoder/ms-marco-MiniLM-L6-v2"),
]


def load_questions() -> list[dict]:
    with QUESTIONS.open(encoding="utf-8") as f:
        return [json.loads(line) for line in f if line.strip()]


def first_hit(paths: list[str], expected: list[str]) -> int | None:
    return next((i for i, p in enumerate(paths, 1) if p in expected), None)


def evaluate(retriever: Retriever, questions: list[dict], mode: str) -> list[dict]:
    rows = []
    for item in questions:
        t0 = time.perf_counter()
        hits = retriever.search(item["q"], top_k=K, mode=mode)
        ms = (time.perf_counter() - t0) * 1000
        paths = [h.chunk.path for h in hits]
        rows.append({**item, "rank": first_hit(paths, item["expected"]), "ms": ms, "got": paths})
    return rows


def summarize(rows: list[dict]) -> dict:
    n = len(rows)
    return {
        "r1": sum(r["rank"] == 1 for r in rows) / n,
        "r5": sum(r["rank"] is not None for r in rows) / n,
        "mrr": sum(1 / r["rank"] for r in rows if r["rank"]) / n,
        "ms": statistics.median(r["ms"] for r in rows),
    }


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--misses", action="store_true")
    args = parser.parse_args()

    questions = load_questions()
    retriever = Retriever()
    retriever.embedder.encode(["warm up"])

    lines = [
        f"| Mode | Recall@{K} (all {len(questions)}) | Recall@{K} broad | Recall@{K} specific "
        "| Recall@1 | MRR | Median latency |",
        "|---|---|---|---|---|---|---|",
    ]
    for label, mode, model in CONFIGS:
        if model:
            retriever.rerank_model = model
            retriever.reranker.predict([("warm up", "warm up")])  # keep loading out of timings
        rows = evaluate(retriever, questions, mode)
        a = summarize(rows)
        b = summarize([r for r in rows if r["set"] == "broad"])
        s = summarize([r for r in rows if r["set"] == "specific"])
        lines.append(
            f"| {label} | **{a['r5']:.0%}** | {b['r5']:.0%} | {s['r5']:.0%} "
            f"| {a['r1']:.0%} | {a['mrr']:.2f} | {a['ms']:,.0f} ms |"
        )
        print(lines[-1], flush=True)
        if args.misses:
            for r in rows:
                if r["rank"] is None:
                    print(f"    miss: {r['q']}\n          got {r['got'][:3]}")
    retriever.rerank_model = config.RERANK_MODEL

    n_broad = sum(q["set"] == "broad" for q in questions)
    note = (
        f"\n\n{len(questions)} hand-written questions ({n_broad} broad, "
        f"{len(questions) - n_broad} specific), CPU only, "
        "top 50 from each retriever fused with RRF (k=60), reranker sees the top 20.\n"
        "Generated by `python eval/run_eval.py`.\n"
    )
    RESULTS.write_text("\n".join(lines) + note, encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
